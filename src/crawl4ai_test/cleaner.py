from pathlib import Path
import re
import json


# ============================================================
# PATHS
# ============================================================

INPUT_DIR = Path.cwd() / "output"
OUTPUT_DIR = Path.cwd() / "cleaned"


# ============================================================
# DOCUMENT CLASSIFICATION
# ============================================================

def get_document_type(filename: str) -> str:
    """
    Determine the type of document from the Crawl4AI filename.

    Examples:
        0002_products_x.md
        0191_collections_frontpage.md
        0189_pages_contact.md
        0208_blogs_news.md
        0000_agents_md.md
    """

    if "_agents_md" in filename:
        return "agent_infrastructure"

    if "_products_" in filename:
        return "product"

    if "_collections_" in filename:
        return "collection"

    if "_pages_" in filename:
        return "page"

    if "_blogs_" in filename:
        return "blog"

    if "_policies_" in filename:
        return "policy"

    return "other"


# ============================================================
# MARKDOWN NORMALIZATION
# ============================================================

def unescape_markdown(text: str) -> str:
    """
    Normalize escaped Markdown generated by Crawl4AI.

    Examples:

        \\# Product
            ↓
        # Product

        **# Product**
            ↓
        # Product
    """

    replacements = {
        r"\#": "#",
        r"\*": "*",
        r"\_": "_",
        r"\(": "(",
        r"\)": ")",
        r"\[": "[",
        r"\]": "]",
        r"\.": ".",
        r"\!": "!",
        r"\-": "-",
        r"\+": "+",
        r"\>": ">",
        r"\|": "|",
    }

    for old, new in replacements.items():
        text = text.replace(old, new)

    # HTML non-breaking space
    text = text.replace("&#x20;", " ")

    # Convert bold-wrapped headings into normal headings.
    #
    # **# Product**
    # **## Description**
    #
    # becomes:
    #
    # # Product
    # ## Description

    text = re.sub(
        r"^\*\*(#+\s.*?)\*\*$",
        r"\1",
        text,
        flags=re.MULTILINE,
    )

    return text


# ============================================================
# SHOPIFY NAVIGATION / UI
# ============================================================

def is_navigation_line(line: str) -> bool:
    """
    Detect obvious Shopify navigation and storefront UI.

    Keep this list conservative so we don't accidentally
    remove useful product information.
    """

    text = line.strip().lower()

    navigation_terms = [
        # Navigation
        "skip to content",
        "skip to product information",
        "log in",

        # Cart
        "item added to your cart",
        "view cart",
        "check out",
        "continue shopping",

        # Media / sharing
        "open media",
        "close share",
        "copy link",
        "view full details",

        # Quantity controls
        "decrease quantity",
        "increase quantity",
        "quantity quantity",

        # Pickup UI
        "couldn't load pickup availability",

        # Browser/UI messages
        "choosing a selection results in a full page refresh",
        "opens in a new window",

        # Product-page buttons
        "add to cart",
        "buy it now",
        "refresh",

        # Share UI
        "share",
        "link",
    ]

    return any(
        term in text
        for term in navigation_terms
    )


# ============================================================
# SHOPIFY FOOTER
# ============================================================

def is_footer_line(line: str) -> bool:
    """
    Detect the actual Shopify footer.

    IMPORTANT:
    Avoid generic terms such as:
        'your name'
        'email address'
        'phone optional'

    Those can be legitimate product customization fields.
    """

    text = line.strip().lower()

    footer_terms = [
        "let's connect",

        "have an idea? let's shape it.",

        "questions, custom ideas, or something completely new?",

        "prefer email?",

        "drop us a line.",

        "follow us for behind-the-scenes prints & drops",

        "powered by shopify",

        "privacy policy",

        "refund policy",

        "shipping policy",

        "contact information",

        "terms of service",

        "© 2026, pharox3d",
    ]

    return any(
        term in text
        for term in footer_terms
    )


# ============================================================
# IMAGE / ASSET DETECTION
# ============================================================

def is_image_or_asset(line: str) -> bool:
    """
    Detect image-only or asset-only Markdown lines.
    """

    text = line.strip()

    # Markdown image
    if re.match(
        r"^!\[.*\]\(.*\)$",
        text,
    ):
        return True

    # Image URL
    if re.search(
        r"\.(jpg|jpeg|png|webp|gif|svg)(\?.*)?$",
        text,
        re.IGNORECASE,
    ):
        return True

    return False


# ============================================================
# MARKDOWN LINKS
# ============================================================

def remove_markdown_links(line: str) -> str:
    """
    Keep visible text while removing URLs.

    Example:

        [Home](https://pharox3d.com/)

    becomes:

        Home
    """

    return re.sub(
        r"\[([^\]]+)\]\([^)]+\)",
        r"\1",
        line,
    )


# ============================================================
# PRODUCT CLEANING
# ============================================================

def clean_product(lines: list[str]) -> list[str]:
    """
    Clean a Shopify product page.

    Keep content starting from the first H1
    until the actual footer begins.
    """

    cleaned = []

    content_started = False
    footer_started = False

    for line in lines:

        stripped = line.strip()

        # ----------------------------------------------------
        # Empty lines
        # ----------------------------------------------------

        if not stripped:

            if (
                content_started
                and not footer_started
            ):
                cleaned.append("")

            continue

        # ----------------------------------------------------
        # Navigation / UI
        # ----------------------------------------------------

        if is_navigation_line(line):
            continue

        # ----------------------------------------------------
        # Images
        # ----------------------------------------------------

        if is_image_or_asset(line):
            continue

        # ----------------------------------------------------
        # Start at first H1
        # ----------------------------------------------------

        if (
            stripped.startswith("# ")
            and not content_started
        ):
            content_started = True

        # Ignore everything before product content
        if not content_started:
            continue

        # ----------------------------------------------------
        # Footer
        # ----------------------------------------------------

        if is_footer_line(line):
            footer_started = True
            continue

        if footer_started:
            continue

        # ----------------------------------------------------
        # Remove URLs but preserve visible text
        # ----------------------------------------------------

        line = remove_markdown_links(line)

        cleaned.append(line)

    return cleaned


# ============================================================
# GENERIC DOCUMENT CLEANING
# ============================================================

def clean_generic(lines: list[str]) -> list[str]:
    """
    Clean collections, pages and blog posts.
    """

    cleaned = []

    footer_started = False

    for line in lines:

        stripped = line.strip()

        # ----------------------------------------------------
        # Empty lines
        # ----------------------------------------------------

        if not stripped:

            if not footer_started:
                cleaned.append("")

            continue

        # ----------------------------------------------------
        # Images
        # ----------------------------------------------------

        if is_image_or_asset(line):
            continue

        # ----------------------------------------------------
        # Navigation
        # ----------------------------------------------------

        if is_navigation_line(line):
            continue

        # ----------------------------------------------------
        # Footer
        # ----------------------------------------------------

        if is_footer_line(line):
            footer_started = True
            continue

        if footer_started:
            continue

        # ----------------------------------------------------
        # Remove URLs but preserve visible text
        # ----------------------------------------------------

        line = remove_markdown_links(line)

        cleaned.append(line)

    return cleaned


# ============================================================
# DUPLICATE REMOVAL
# ============================================================

def remove_duplicate_lines(
    lines: list[str],
) -> list[str]:
    """
    Remove consecutive duplicate lines.
    """

    result = []

    previous = None

    for line in lines:

        normalized = line.strip()

        if (
            normalized
            and normalized == previous
        ):
            continue

        result.append(line)

        if normalized:
            previous = normalized

    return result


# ============================================================
# WHITESPACE NORMALIZATION
# ============================================================

def normalize_markdown(
    lines: list[str],
) -> str:
    """
    Remove excessive blank lines and trailing whitespace.
    """

    result = []

    blank_count = 0

    for line in lines:

        line = line.rstrip()

        if not line.strip():

            blank_count += 1

            if blank_count <= 2:
                result.append("")

        else:

            blank_count = 0
            result.append(line)

    return "\n".join(result).strip()


# ============================================================
# COMPLETE CLEANING PIPELINE
# ============================================================

def clean_markdown(
    text: str,
    document_type: str,
) -> str:
    """
    Run the complete cleaning pipeline.
    """

    # --------------------------------------------------------
    # 1. Normalize escaped Markdown
    # --------------------------------------------------------

    text = unescape_markdown(text)

    lines = text.splitlines()

    # --------------------------------------------------------
    # 2. Document-specific cleaning
    # --------------------------------------------------------

    if document_type == "product":

        lines = clean_product(lines)

    else:

        lines = clean_generic(lines)

    # --------------------------------------------------------
    # 3. Remove consecutive duplicates
    # --------------------------------------------------------

    lines = remove_duplicate_lines(lines)

    # --------------------------------------------------------
    # 4. Normalize whitespace
    # --------------------------------------------------------

    return normalize_markdown(lines)


# ============================================================
# TITLE EXTRACTION
# ============================================================

def extract_title(
    text: str,
    filename: str,
) -> str:
    """
    Extract the first H1 as the document title.

    If no H1 exists, fall back to the filename.
    """

    for line in text.splitlines():

        line = line.strip()

        if line.startswith("# "):

            return line[2:].strip()

    # --------------------------------------------------------
    # Fallback
    # --------------------------------------------------------

    name = filename.replace(
        ".md",
        "",
    )

    name = re.sub(
        r"^\d+_",
        "",
        name,
    )

    return (
        name
        .replace("_", " ")
        .replace("-", " ")
        .strip()
    )


# ============================================================
# PROCESS ONE FILE
# ============================================================

def process_file(
    file_path: Path,
) -> dict:
    """
    Process one Markdown file.
    """

    raw_text = file_path.read_text(
        encoding="utf-8",
    )

    document_type = get_document_type(
        file_path.name,
    )

    cleaned_text = clean_markdown(
        raw_text,
        document_type,
    )

    title = extract_title(
        cleaned_text,
        file_path.name,
    )

    return {
        "filename": file_path.name,
        "title": title,
        "type": document_type,
        "text": cleaned_text,
    }


# ============================================================
# MAIN
# ============================================================

def main():

    # Create cleaned directory
    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Find raw Markdown files
    files = sorted(
        INPUT_DIR.glob("*.md")
    )

    print(
        f"📂 Input: {INPUT_DIR}"
    )

    print(
        f"📂 Output: {OUTPUT_DIR}"
    )

    print(
        f"📄 Files: {len(files)}"
    )

    print()

    documents = []

    # --------------------------------------------------------
    # Process every document
    # --------------------------------------------------------

    for index, file_path in enumerate(files):

        document = process_file(
            file_path
        )

        # Save cleaned Markdown
        output_file = (
            OUTPUT_DIR /
            file_path.name
        )

        output_file.write_text(
            document["text"],
            encoding="utf-8",
        )

        documents.append(document)

        print(
            f"✅ [{index + 1:03d}/{len(files):03d}] "
            f"{file_path.name} "
            f"→ {document['type']}"
        )

    # --------------------------------------------------------
    # Save metadata
    # --------------------------------------------------------

    metadata_file = (
        OUTPUT_DIR /
        "metadata.json"
    )

    metadata_file.write_text(
        json.dumps(
            documents,
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )

    # --------------------------------------------------------
    # Summary
    # --------------------------------------------------------

    print()

    print("🎉 Cleaning complete!")

    print(
        f"📄 Cleaned documents: {len(documents)}"
    )

    print(
        f"📂 Location: {OUTPUT_DIR}"
    )

    print(
        f"🧠 Metadata: {metadata_file}"
    )


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()